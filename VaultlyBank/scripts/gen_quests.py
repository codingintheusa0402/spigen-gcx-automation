def opt(title, note, **effect):
    return dict(title=title, note=note, effect=effect)
def flow(cp, memo, amount, freq="monthly", day=25, cat="transfer", hour=10, salary=False, months=None):
    return dict(cp=cp, memo=memo, amount=amount, freq=freq, day=day, cat=cat, hour=hour, salary=salary, months=months)
def gamble(chance, win, lose, months, winText, loseText, cp, winFlow=None, loseFlow=None, loseSalaryPause=0, loseFine=0):
    return dict(chance=chance, win=win, lose=lose, months=months, winText=winText, loseText=loseText, cp=cp, winFlow=winFlow, loseFlow=loseFlow,
                loseSalaryPause=loseSalaryPause, loseFine=loseFine)

